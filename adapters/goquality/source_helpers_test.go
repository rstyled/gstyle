package goquality

import (
	"context"
	"encoding/json"
	"os"
	"path/filepath"
	"reflect"
	"testing"

	"github.com/rstyled/gstyle/domain/quality"
)

func TestLoadedSourceHelpersCrossPackageBoundaries(t *testing.T) {
	root := qualitySourceModule(t, []byte(`package repro
import "example.com/quality-repro/lib"
func PureCaller(t lib.Table)string{return t.Text()}
func JSONCaller(){lib.JSON()}
func IOCaller(){lib.IO()}
func GlobalCaller(){lib.Global()}
func MutationCaller(p *int){lib.Set(p)}
func FieldCaller(b *lib.Box){b.Put()}
func BorrowedFieldCaller(m map[string]int){b:=lib.Box{Values:m};b.Put()}
func FieldSortCaller(b *lib.Box){b.Sort()}
func UnknownWriteCaller(p **int){lib.UnknownWrite(p)}
func UnsafeCaller(p *int){lib.Unsafe(p)}
func RecursiveCaller(){lib.Recurse()}
func MutualCaller()bool{return lib.Even(4)}
func RecursiveIOCaller(){lib.RecursiveIO()}
func DynamicCaller(cb func()){lib.Invoke(cb)}
func GeneratedCaller()int{return lib.Generated(7)}
func PanicCaller(){lib.Fail()}
func PanicOwned(){p:=new(int);lib.FailAndSet(p)}
func PanicShared(p *int){lib.FailAndSet(p)}
func PanicWrapped(){lib.WrappedFail()}
`))
	files := map[string]string{
		"lib/helper.go": `package lib
import("fmt";"encoding/json";"slices";"unsafe";"example.com/quality-repro/core")
type Table struct{Value string}
func(t Table)Text()string{return core.Identity(t.Value)}
func JSON(){json.Marshal(struct{Value string}{})}
func IO(){fmt.Println("hello")}
var Counter int
func Global(){Counter++}
func Set(p *int){*p=1}
type Box struct{Values map[string]int;Items []int}
func(b *Box)Put(){b.Values["x"]=1}
func(b *Box)Sort(){slices.Sort(b.Items)}
func UnknownWrite(p **int){**p=1}
func Unsafe(p *int){_ = unsafe.Pointer(p)}
func Recurse(){Recurse()}
func Even(n int)bool{if n==0{return true};return Odd(n-1)}
func Odd(n int)bool{if n==0{return false};return Even(n-1)}
func RecursiveIO(){RecursiveIO();fmt.Println("still IO")}
func Invoke(cb func()){cb()}
func Fail(){panic("bad")}
func FailAndSet(p *int){if p==nil{panic("nil")};*p=1}
func WrappedFail(){Fail()}
`,
		"lib/generated.go": `// Code generated by fixture. DO NOT EDIT.
package lib
func Generated(v int)int{return v}
`,
		"core/value.go": `package core
func Identity(v string)string{return v}
`,
	}
	for path, source := range files {
		name := filepath.Join(root, path)
		if err := os.MkdirAll(filepath.Dir(name), 0700); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(name, []byte(source), 0600); err != nil {
			t.Fatal(err)
		}
	}
	facts, err := (Analyzer{Root: root}).Extract(context.Background(), nil)
	if err != nil {
		t.Fatal(err)
	}
	report, err := quality.Evaluate(facts, quality.DefaultConfig())
	if err != nil {
		t.Fatal(err)
	}
	for _, tc := range []struct {
		name     string
		kind     quality.Kind
		complete bool
	}{
		{"PureCaller", quality.None, true}, {"JSONCaller", quality.None, true}, {"GeneratedCaller", quality.None, true},
		{"IOCaller", quality.UnknownEffect, false}, {"GlobalCaller", quality.UnknownEffect, false}, {"MutationCaller", quality.MutationEffect, true},
		{"FieldCaller", quality.MutationEffect, true}, {"BorrowedFieldCaller", quality.MutationEffect, true}, {"FieldSortCaller", quality.UnknownEffect, false},
		{"UnknownWriteCaller", quality.UnknownEffect, false}, {"UnsafeCaller", quality.UnknownEffect, false},
		{"RecursiveCaller", quality.None, true}, {"MutualCaller", quality.None, true},
		{"RecursiveIOCaller", quality.UnknownEffect, false}, {"DynamicCaller", quality.UnknownEffect, false},
		{"PanicCaller", quality.Panic, true}, {"PanicOwned", quality.Panic, true}, {"PanicWrapped", quality.Panic, true},
	} {
		t.Run(tc.name, func(t *testing.T) {
			result := resultNamed(t, report, tc.name)
			if result.Complete != tc.complete {
				t.Fatalf("coverage: %+v", result)
			}
			if tc.kind == quality.None {
				if len(result.Effects) != 0 || result.DensityMilli != 0 {
					t.Fatalf("read-only body reported effects: %+v", result)
				}
				return
			}
			if len(result.Effects) != 1 || result.Effects[0].Kind != tc.kind {
				t.Fatalf("effects: %+v", result.Effects)
			}
			if result.Effects[0].Line != findFunction(t, facts, tc.name).Calls[0].Line {
				t.Fatal("effect lost caller location")
			}
		})
	}
	shared := resultNamed(t, report, "PanicShared")
	kinds := map[quality.Kind]bool{}
	for _, effect := range shared.Effects {
		kinds[effect.Kind] = true
	}
	if !shared.Complete || len(shared.Effects) != 2 || !kinds[quality.Panic] || !kinds[quality.MutationEffect] {
		t.Fatalf("shared write or panic lost: %+v", shared)
	}
	field := findFunction(t, facts, "FieldCaller")
	if !field.Calls[0].Local || len(field.Helpers) != 1 {
		t.Fatal("known field mutation body was not retained")
	}
	writes := field.Helpers[0].Mutations
	if len(writes) != 1 || writes[0].Provenance != quality.External || writes[0].Parameter != nil {
		t.Fatalf("unbound external mutation changed: %+v", writes)
	}
	if findFunction(t, facts, "UnknownWriteCaller").Calls[0].Local {
		t.Fatal("unknown unbound mutation was admitted")
	}
	override := quality.DefaultConfig()
	override.Weights.Panic = 2
	override.Prefixes = append(override.Prefixes, quality.Prefix{Path: "example.com/quality-repro/core.Identity", Kind: quality.IO}, quality.Prefix{Path: field.Calls[0].Callee, Kind: quality.IO}, quality.Prefix{Path: "example.com/quality-repro/lib.WrappedFail", Kind: quality.IO})
	overridden, err := quality.Evaluate(facts, override)
	if err != nil {
		t.Fatal(err)
	}
	if got := resultNamed(t, overridden, "PureCaller"); len(got.Effects) != 1 || got.Effects[0].Kind != quality.IO {
		t.Fatal("read-only proof hid a policy override")
	}
	if got := resultNamed(t, overridden, "FieldCaller"); len(got.Effects) != 1 || got.Effects[0].Kind != quality.IO {
		t.Fatal("mutation evidence hid a policy override")
	}
	if got := resultNamed(t, overridden, "PanicWrapped"); len(got.Effects) != 1 || got.Effects[0].Kind != quality.IO {
		t.Fatal("panic evidence hid a policy override")
	}
	if got := resultNamed(t, overridden, "PanicOwned"); got.DensityMilli != 1000 {
		t.Fatalf("panic weight ignored: %+v", got)
	}
	encoded, err := json.Marshal(facts)
	if err != nil {
		t.Fatal(err)
	}
	var restored []quality.Function
	if err := json.Unmarshal(encoded, &restored); err != nil {
		t.Fatal(err)
	}
	replay, err := quality.Evaluate(restored, quality.DefaultConfig())
	if err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(report, replay) {
		t.Fatal("saved cross-package evidence changed")
	}
	limited, err := (Analyzer{Root: root}).Extract(context.Background(), []string{"input.go"})
	if err != nil {
		t.Fatal(err)
	}
	limitedReport, err := quality.Evaluate(limited, quality.DefaultConfig())
	if err != nil {
		t.Fatal(err)
	}
	missing := resultNamed(t, limitedReport, "PureCaller")
	if missing.Complete || missing.UnclassifiedCalls != 1 {
		t.Fatal("unloaded dependency was treated as read-only")
	}
}
