func TestGuardRejectsInvalidInputs(t *testing.T) {
	root := testRepository(t)
	gitTest(t, root, "add", ".")
	gitTest(t, root, "commit", "-m", "base")
	t.Chdir(root)
	for _, args := range [][]string{{"--base", "missing"}, {"--format", "unknown"}, {"--config", "missing.toml"}} {
		if err := Run(context.Background(), args, &bytes.Buffer{}); err == nil || errors.Is(err, ErrFindings) {
			t.Errorf("%v: %v", args, err)
		}
	}
	writeFile(t, root, "gstyle.toml", "[guard.comments]\nmode = 'typo'\n")
	if err := Run(context.Background(), nil, &bytes.Buffer{}); err == nil || errors.Is(err, ErrFindings) {
		t.Fatalf("invalid config: %v", err)
	}
}

func TestScannerUsesPhysicalComments(t *testing.T) {
	source := []byte("package p\nvar Text = `// string`\n//line other.go:900\n/* block */\n")
	got, err := scanComments("file.go", source)
	if err != nil || len(got) != 2 || got[1].Line != 4 {
		t.Fatalf("comments=%+v error=%v", got, err)
	}
	if _, err := scanComments("file.go", []byte("package p\n/* unterminated")); err == nil {
		t.Fatal("unterminated comment accepted")
	}
	if _, _, err := takeChange([]string{"R100", "old.go"}); err == nil {
		t.Fatal("incomplete rename accepted")
	}
	if _, _, err := takeChange([]string{"M"}); err == nil {
		t.Fatal("incomplete change accepted")
	}
}

func testRepository(t *testing.T) string {
	t.Helper()
	root := t.TempDir()
	gitTest(t, root, "init")
	gitTest(t, root, "config", "user.name", "Test")
	gitTest(t, root, "config", "user.email", "test@example.com")
	writeFile(t, root, "gstyle.toml", "[guard.comments]\nmode = 'added'\n[[guard.files]]\nid = 'python'\nextensions = ['.py']\nallow_directories = ['verification/lean']\n")
	return root
}

func gitTest(t *testing.T, root string, args ...string) {
	t.Helper()
	command := exec.Command("git", args...)
	command.Dir = root
	if output, err := command.CombinedOutput(); err != nil {
		t.Fatalf("git %v: %v\n%s", args, err, output)
	}
}

func writeFile(t *testing.T, root, name, content string) {
	t.Helper()
	file := filepath.Join(root, name)
	if err := os.MkdirAll(filepath.Dir(file), 0700); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(file, []byte(content), 0600); err != nil {
		t.Fatal(err)
	}
}
