func TestGuardChecksRepositoryWithoutGoModule(t *testing.T) {
	root := testRepository(t)
	writeFile(t, root, "old.go", "package p\n// existing\nvar Value = 1\n")
	writeFile(t, root, "legacy.py", "pass\n")
	gitTest(t, root, "add", ".")
	gitTest(t, root, "commit", "-m", "base")
	if err := os.Remove(filepath.Join(root, "legacy.py")); err != nil {
		t.Fatal(err)
	}
	writeFile(t, root, "old.go", "package p\n// existing\nvar Value = 2\n")
	writeFile(t, root, "new file.go", "package p\nvar URL = `https://example.com/* text */`\n// prohibited\n")
	writeFile(t, root, "build.py", "pass\n")
	writeFile(t, root, "verification/lean/check.py", "pass\n")
	writeFile(t, root, "verification/lean-copy/check.py", "pass\n")
	t.Chdir(root)
	var output bytes.Buffer
	err := Run(context.Background(), []string{"--base", "HEAD", "--format", "json"}, &output)
	if !errors.Is(err, ErrFindings) {
		t.Fatalf("error=%v output=%s", err, output.String())
	}
	var got report
	if err := json.Unmarshal(output.Bytes(), &got); err != nil {
		t.Fatal(err)
	}
	if got.SchemaVersion != 1 || len(got.Findings) != 3 {
		t.Fatalf("report: %s", output.String())
	}
	if got.Findings[1].RuleID != "source_comment" || got.Findings[1].Line != 3 || got.Findings[1].Path != "new file.go" {
		t.Fatalf("comment finding: %+v", got.Findings)
	}
	output.Reset()
	err = Run(context.Background(), []string{"--base", "HEAD", "--format", "sarif"}, &output)
	if !errors.Is(err, ErrFindings) || !strings.Contains(output.String(), "gstyle/guard/") {
		t.Fatalf("SARIF error=%v output=%s", err, output.String())
	}
	writeFile(t, root, "new file.go", "package p\nvar URL = `https://example.com/* text */`\n")
	for _, name := range []string{"build.py", "verification/lean-copy/check.py"} {
		if err := os.Remove(filepath.Join(root, name)); err != nil {
			t.Fatal(err)
		}
	}
	output.Reset()
	if err := Run(context.Background(), []string{"--base", "HEAD"}, &output); err != nil {
		t.Fatalf("fixed: %v %s", err, output.String())
	}
}

